/**
 * 「自分のタグ × 相手のタグ → 優位ポイント」の対決ルール。
 *
 * 組み合わせごとの手書き解説を蒸留したもので、マッチアップ解説コンテンツの正本。
 * フォーメーションを1種増やしたときの執筆量が「既存全件との組み合わせ分」ではなく
 * 「足りないルールの数」で済むようにするための構造である。
 */
export interface MatchupRule {
  id: string;
  /** このルールが語る戦術テーマ。同一テーマからは1件しか発火しない（RuleTheme 参照） */
  theme: RuleTheme;
  /** 優位を得る側が持つべきタグ（すべて満たす必要がある。空配列なら常に成立） */
  selfTags: readonly FormationTag[];
  /** 相手が持つべきタグ（すべて満たす必要がある。空配列なら常に成立） */
  opponentTags: readonly FormationTag[];
  /**
   * 優位ポイントの文（箇条書き1行分）。複数の言い回しを持ち、ペアIDのハッシュで
   * 決定的に1つ選ぶ（matchupGenerator.ts）。どれが選ばれても意味が変わらないこと。
   *
   * 注意: 用語集（soccerTerms.ts）の収録語は「実際の文言に登場すること」が
   * soccerTerms.test.ts で検証される。用語を担うルールは、どの言い回しが選ばれても
   * その用語が残るよう、全要素に同じ用語を含めること。
   */
  advantages: readonly string[];
  /**
   * 総合判定の見出し（overallReason）に埋め込む根拠。体言止め（「〜点」）で書き、
   * 「{名前}は、{reason}と{reason}が効いており…」の形にそのまま差し込めるようにする。
   */
  reason: string;
  /**
   * 総合優劣への寄与。原則1。
   *
   * 注意: 同一テーマの間引き（matchupGenerator の applicableRules）は**配列順だけを見て
   * score を見ない**。score を 2 以上にしたルールを同テーマの後方へ置くと、score=1 の
   * 先行ルールに吸収されて総合判定が静かに下振れする。原則どおり 1 で揃えている限り無害
   */
  score: number;
}


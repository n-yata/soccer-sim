/**
 * ルールが語る戦術テーマ。
 *
 * **1つの噛み合わせで、同一テーマから発火するのは1件だけ**（matchupGenerator.ts が
 * 配列順で先に来たものを残し、残りを落とす）。これが無いと、同じ戦術を別の切り口で
 * 書いた複数のルールが同時に当たり、(1) ほぼ同じ文が並ぶ (2) 優劣スコアが二重計上される、
 * という二重の事故が起きる。しかも文字列は違うので重複検知をすり抜け、テストは緑のまま
 * 判定だけが静かに片側へ歪む。
 *
 * 事故は2つの経路で起きるため、テーマはその両方を塞ぐ:
 * - **条件の包含**: あるルールの条件が別のルールの上位集合になっている
 * - **タグの共起**: 条件は独立でも、実データ上つねに同じフォーメーションが両方のタグを持つ
 *   （例: 4-4-2 は `中盤フラット4枚` と `ライン間が空く` を常に併せ持つ）
 *
 * 後者は「ルール単体の定義」を見ても分からない。テーマで括るのが唯一の確実な防ぎ方である。
 */
